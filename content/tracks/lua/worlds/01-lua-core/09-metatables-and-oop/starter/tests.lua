local t = require("oxide.test")
local pos = require("position")

t.test("instances_share_methods", function()
  local a, b = pos.new(0, 0), pos.new(3, 4)
  t.eq(a:manhattan(b), 7)
  t.is_nil(rawget(a, "manhattan"), "the method is not copied into each object")
  t.truthy(rawequal(a.manhattan, b.manhattan), "both objects use the same function")
end)

t.test("read_only_table_rejects_writes", function()
  local cfg = pos.read_only({stack_size = 50})
  t.eq(cfg.stack_size, 50, "reading works")
  t.raises(function() cfg.stack_size = 1 end, "read-only")
  t.raises(function() cfg.new_key = 1 end, "read-only")
  t.eq(cfg.stack_size, 50, "unchanged")
end)

t.test("vector_adds_with_plus", function()
  local c = pos.new(1, 2) + pos.new(10, 20)
  t.eq(c.x, 11)
  t.eq(c.y, 22)
  t.eq(c:manhattan(pos.new(0, 0)), 33, "the sum is a Position too")
end)

t.test("tostring_formats_vector", function()
  t.eq(tostring(pos.new(1, 2)), "(1, 2)")
  t.eq(tostring(pos.new(-0.5, 3)), "(-0.5, 3)")
end)
