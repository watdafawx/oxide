local t = require("oxide.test")
local n = require("numbers")

t.test("only_nil_and_false_are_falsy", function()
  t.truthy(n.is_falsy(nil), "nil")
  t.truthy(n.is_falsy(false), "false")
  t.falsy(n.is_falsy(0), "0 is truthy in Lua")
  t.falsy(n.is_falsy(""), "the empty string is truthy")
end)

t.test("halves_and_floors_correctly", function()
  t.eq(n.half(7), 3.5)
  t.eq(n.floor_half(7), 3)
  t.eq(n.floor_half(10), 5)
end)

t.test("formats_whole_numbers", function()
  t.eq(n.whole(5), "5")
  t.eq(n.whole(10 / 2), "5")
  t.eq(n.whole(-3), "-3")
end)
