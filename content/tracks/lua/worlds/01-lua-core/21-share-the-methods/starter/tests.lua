local t = require("oxide.test")
local Pantry = require("pantry_object")

t.test("pantries_share_their_methods", function()
  local a, b = Pantry.new({eggs = 2}), Pantry.new({flour = 5})
  t.eq(a:count_of("eggs"), 2)
  t.eq(b:count_of("flour"), 5)
  t.is_nil(rawget(a, "count_of"), "the method is not copied into each pantry")
  t.truthy(rawequal(a.count_of, b.count_of), "both pantries use the same function")
end)

t.test("adding_changes_only_this_pantry", function()
  local a, b = Pantry.new({eggs = 2}), Pantry.new({eggs = 2})
  a:add("eggs", 3)
  a:add("milk", 1)
  t.eq(a:count_of("eggs"), 5)
  t.eq(a:count_of("milk"), 1)
  t.eq(b:count_of("eggs"), 2, "the other pantry is unchanged")
end)
