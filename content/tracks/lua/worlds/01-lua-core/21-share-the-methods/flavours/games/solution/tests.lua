local t = require("oxide.test")
local Chest = require("chest_object")

t.test("chests_share_their_methods", function()
  local a, b = Chest.new({coal = 2}), Chest.new({stone = 5})
  t.eq(a:count_of("coal"), 2)
  t.eq(b:count_of("stone"), 5)
  t.is_nil(rawget(a, "count_of"), "the method is not copied into each chest")
  t.truthy(rawequal(a.count_of, b.count_of), "both chests use the same function")
end)

t.test("adding_changes_only_this_chest", function()
  local a, b = Chest.new({coal = 2}), Chest.new({coal = 2})
  a:add("coal", 3)
  a:add("wood", 1)
  t.eq(a:count_of("coal"), 5)
  t.eq(a:count_of("wood"), 1)
  t.eq(b:count_of("coal"), 2, "the other chest is unchanged")
end)
