local t = require("oxide.test")
local calc = require("calc")

local function texts(tokens)
  local out = {}
  for i, tok in ipairs(tokens) do out[i] = tok.text end
  return out
end

t.test("tokenizes_a_cost_formula", function()
  local toks = calc.tokenize("12 + 3.5 * (2 - 1) / 4 ^ 2")
  t.deep_eq(texts(toks), {"12", "+", "3.5", "*", "(", "2", "-", "1", ")", "/", "4", "^", "2"})
  t.eq(toks[1].kind, "num")
  t.eq(toks[1].value, 12)
  t.eq(toks[3].value, 3.5)
  t.eq(toks[2].kind, "op")
  t.eq(toks[5].kind, "(")
  t.eq(toks[3].pos, 6, "pos is the 1-based character index")
  t.deep_eq(calc.tokenize(""), {})
end)

t.test("multiplies_before_adding", function()
  t.eq(calc.eval("2 + 3 * 4"), 14, "* before +")
  t.eq(calc.eval("2 * 3 + 4"), 10)
  t.eq(calc.eval("10 - 4 - 3"), 3, "minus goes left to right")
  t.eq(calc.eval("8 / 4 / 2"), 1, "so does divide")
  t.eq(calc.eval("2 ^ 3 ^ 2"), 512, "^ goes right to left")
  t.eq(calc.eval("2 * 3 ^ 2"), 18, "^ before *")
  t.eq(calc.eval("1 + 2 + 3 * 4 - 5"), 10)
end)

t.test("handles_brackets_and_negatives", function()
  t.eq(calc.eval("(1 + 2) * 3"), 9)
  t.eq(calc.eval("((4))"), 4)
  t.eq(calc.eval("-(1 + 2)"), -3)
  t.eq(calc.eval("2 * -3"), -6)
  t.eq(calc.eval("--4"), 4)
  t.eq(calc.eval("-2 ^ 2"), -4, "unary minus binds looser than ^")
  t.eq(calc.eval("2 ^ -1"), 0.5)
end)

t.test("reads_item_counts", function()
  t.eq(calc.eval("plates * 2 + cables", {plates = 3, cables = 1}), 7)
  t.eq(calc.eval("craft_time ^ 2", {craft_time = 4}), 16, "underscores are fine in names")
  t.raises(function() calc.eval("x + 1", {}) end, "unknown variable 'x'")
  t.raises(function() calc.eval("y") end, "unknown variable 'y'", "no environment at all")
end)

t.test("points_at_the_bad_character", function()
  t.raises(function() calc.eval("2 + * 3") end, "position 5")
  t.raises(function() calc.eval("2 + * 3") end, "unexpected '*'")
  t.raises(function() calc.eval("(1 + 2") end, "position 7")
  t.raises(function() calc.eval("(1 + 2") end, "expected ')'")
  t.raises(function() calc.eval("2 $ 3") end, "position 3")
  t.raises(function() calc.eval("2 $ 3") end, "unexpected character '$'")
  t.raises(function() calc.eval("1 2") end, "position 3")
  t.raises(function() calc.eval("") end, "unexpected end of input")
  t.raises(function() calc.eval("3 +") end, "syntax error at position 4")
end)

t.test("refuses_to_divide_by_zero", function()
  t.raises(function() calc.eval("1 / 0") end, "division by zero")
  t.raises(function() calc.eval("5 / (3 - 3)") end, "division by zero")
  t.eq(calc.eval("0 / 5"), 0)
  t.eq(calc.eval("1 / 4"), 0.25)
end)
